// presetInputs fills answers from flags first, then the matching
// environment variables, and reports which prompts are already
// answered. A flag wins over its variable.
func presetInputs(a *answers, sourceFlag, sourceDirFlag string) error {
	a.given = map[string]bool{}
	get := func(flagVal, envName string) (string, bool) {
		if flagVal != "" {
			return flagVal, true
		}
		if v, ok := os.LookupEnv(envName); ok {
			return v, true
		}
		return "", false
	}
	if v, ok := get(sourceFlag, "EVESYNAPSE_SOURCE"); ok {
		switch strings.ToLower(strings.TrimSpace(v)) {
		case sourceBuild, sourceDownload:
			a.source = strings.ToLower(strings.TrimSpace(v))
			a.given["source"] = true
		default:
			return fmt.Errorf("EVESYNAPSE_SOURCE (or --source) must be build or download, not %q", v)
		}
	}
	if v, ok := get(sourceDirFlag, "EVESYNAPSE_SOURCE_DIR"); ok {
		a.sourceDir = expandPath(v)
		a.given["sourceDir"] = true
	}
	if v, ok := os.LookupEnv("EVESYNAPSE_DATABASE_URL"); ok && v != "" {
		a.dbLocal = false
		a.databaseURL = v
		a.orgDB = orgNew
		a.given["databaseURL"] = true
	}
	if v, ok := os.LookupEnv("EVESYNAPSE_EVE_CLIENT_ID"); ok {
		a.clientID = v
		a.given["clientID"] = true
		if v == "" {
			a.orgClientID = orgSkipped
		} else {
			a.orgClientID = orgNew
		}
	}
	if v, ok := os.LookupEnv("EVESYNAPSE_EVE_CLIENT_SECRET"); ok {
		a.clientSecret = v
		a.given["clientSecret"] = true
		if v == "" {
			a.orgClientSecret = orgSkipped
		} else {
			a.orgClientSecret = orgNew
		}
	}
	if v, ok := os.LookupEnv("EVESYNAPSE_EVE_CALLBACK_URL"); ok {
		a.callback = v
		a.given["callback"] = true
		a.orgCallback = orgNew
	}
	if v, ok := os.LookupEnv("EVESYNAPSE_ESI_CONTACT"); ok {
		a.contact = v
		a.given["contact"] = true
		if v == "" {
			a.orgContact = orgSkipped
		} else {
			a.orgContact = orgNew
		}
	}
	return nil
}

func main() {
	dryRun := flag.Bool("dry-run", false, "run the prompts and review, then stop before installing")
	sourceFlag := flag.String("source", "", "install source: build or download")
	sourceDirFlag := flag.String("source-dir", "", "source folder for --source=build")
	flag.Parse()

	a := answers{dbLocal: true}
	a.detectExisting()
	if err := presetInputs(&a, *sourceFlag, *sourceDirFlag); err != nil {
		fmt.Fprintln(os.Stderr, "installer:", err)
		os.Exit(1)
	}
	// A real install on Linux runs setup.sh, which needs root;
	// say so before the prompts rather than after them. A dry
	// run needs nothing installed, so it runs as anyone.
	if isLinux() && !*dryRun && os.Geteuid() != 0 {
		fmt.Fprintln(os.Stderr, "installer: run this with sudo: sudo ./installer")
		os.Exit(1)
	}
	defer func() {
		if a.downloadDir != "" {
			os.RemoveAll(a.downloadDir)
		}
	}()

	if isTerminal() {
		runTUI(&a, *dryRun)
		return
	}
	plainRun(&a, *dryRun)
}

func isTerminal() bool {
	fi, err := os.Stdout.Stat()
	if err != nil {
		return false
	}
	return fi.Mode()&os.ModeCharDevice != 0
}
