const (
	sourceBuild    = "build"
	sourceDownload = "download"
)

// origin says where a review value came from.
type origin int

const (
	orgNew       origin = iota // typed or chosen in this run
	orgPresent                 // already in the existing .env
	orgDetected                // autodetected as optimal on this machine
	orgGenerated               // generated by the installer at install time
	orgSkipped                 // deliberately left blank
	orgDefault                 // unset: the app's built-in default applies
)

func (o origin) String() string {
	switch o {
	case orgPresent:
		return "already present"
	case orgDetected:
		return "autodetected"
	case orgGenerated:
		return "generated"
	case orgSkipped:
		return "skipped"
	case orgDefault:
		return "default"
	default:
		return "new"
	}
}

// answers holds everything the install needs.
type answers struct {
	source     string // build or download
	sourceDir  string // build path: the checkout
	arch       string // detected CPU kind: amd64 or arm64
	installDir string // Linux: /opt/evesynapse; elsewhere: where the binary goes

	dbLocal      bool   // true: provision local PostgreSQL; false: use DATABASE_URL
	databaseURL  string // only when dbLocal is false
	clientID     string
	clientSecret string
	contact      string
	callback     string // EVE_CALLBACK_URL

	// edits holds every other change made on the review screen,
	// and any key cleared there (an empty value).
	edits map[string]string

	// download results, filled when the release is fetched
	release          *releaseInfo
	downloadedBinary string // verified binary on disk, download path
	downloadDir      string // temp dir holding it, removed on exit

	// detected on this machine
	existingEnv   map[string]string // keys in /opt/evesynapse/.env (values for non-secrets)
	existingEnvAt string            // the .env file read, when one exists
	hasLocalPG    bool

	// origins, for the review table's Source column
	orgSourceDir    origin
	orgDB           origin
	orgClientID     origin
	orgClientSecret origin
	orgContact      origin
	orgCallback     origin

	// given records which values came from a flag or an
	// environment variable, so the prompts for them can be
	// skipped. A value the installer detected or defaulted
	// does not count: the operator still sees that prompt.
	given map[string]bool

	startWarning string // a service that would not start, for the done screen
}

// envVars returns the environment variables to pass to setup.sh.
// It only needs to know which database to provision or use; every
// other setting is written by finalEdits after it has run, so no
// secret travels through a child process's environment.
func (a *answers) envVars() []string {
	if a.dbLocal {
		return []string{"EVESYNAPSE_PROVISION_DB=1"}
	}
	// "present" is the sentinel for a DATABASE_URL that already
	// lives in the existing .env: setup.sh leaves it alone.
	if a.databaseURL != "" && a.databaseURL != "present" {
		return []string{"EVESYNAPSE_DATABASE_URL=" + a.databaseURL}
	}
	return nil
}

// maskSecret hides all but the last 4 characters of a secret.
func maskSecret(s string) string {
	if s == "" {
		return "(blank)"
	}
	if len(s) <= 4 {
		return "****"
	}
	return "****" + s[len(s)-4:]
}

// maskDBURL hides the password inside a postgres connection string.
func maskDBURL(u string) string {
	if u == "" {
		return "(blank)"
	}
	rest := strings.TrimPrefix(u, "postgres://")
	rest = strings.TrimPrefix(rest, "postgresql://")
	at := strings.LastIndex(rest, "@")
	if at < 0 {
		return u
	}
	cred, host := rest[:at], rest[at+1:]
	colon := strings.Index(cred, ":")
	if colon < 0 {
		return u
	}
	user := cred[:colon]
	scheme := "postgres://"
	if strings.HasPrefix(u, "postgresql://") {
		scheme = "postgresql://"
	}
	return scheme + user + ":****@" + host
}

// listenAddr is the address the app will bind.
func (a *answers) listenAddr() string {
	if v, ok := a.edits["ADDR"]; ok && v != "" {
		return v
	}
	if v := a.existingEnv["ADDR"]; v != "" {
		return v
	}
	return ":8080"
}

// siteURL is the local address the app answers on after the
// install. The operator's own proxy reaches it from the internet.
func (a *answers) siteURL() string {
	host, port, err := net.SplitHostPort(a.listenAddr())
	if err != nil {
		return "http://127.0.0.1:8080"
	}
	if host == "" || host == "0.0.0.0" || host == "::" {
		host = "127.0.0.1"
	}
	return "http://" + net.JoinHostPort(host, port)
}

// detectExisting fills in what this machine already has: the
// architecture, the install directory, a local PostgreSQL, and
// an existing .env and its values.
func (a *answers) detectExisting() {
	a.arch = targetArch()
	if isLinux() {
		a.installDir = "/opt/evesynapse"
	} else {
		cwd, _ := os.Getwd()
		a.installDir = cwd
	}
	a.hasLocalPG = commandAvailable("psql") || serviceActive("postgresql")

	envPath := "/opt/evesynapse/.env"
	if !isLinux() {
		envPath = filepath.Join(a.installDir, ".env")
	}
	a.existingEnv = map[string]string{}
	if a.edits == nil {
		a.edits = map[string]string{}
	}
	if data, err := os.ReadFile(envPath); err == nil {
		a.existingEnvAt = envPath
		for k, v := range parseEnv(string(data)) {
			if v == "" {
				continue // a blank template line is not a setting
			}
			if k == "DATABASE_URL" && v == templateDatabaseURL {
				continue // the template's placeholder has no password
			}
			// Secrets are recorded as present, never kept.
			if isSecretKey(k) {
				v = "present"
			}
			a.existingEnv[k] = v
		}
	} else {
		// A fresh install stays behind the operator's proxy.
		a.edits["ADDR"] = "127.0.0.1:8080"
	}
	// Prefill from the existing settings file: what is already
	// there stays unless the operator changes it.
	if v, ok := a.existingEnv["EVE_CLIENT_ID"]; ok && a.clientID == "" {
		a.clientID = v
		a.orgClientID = orgPresent
	}
	if _, ok := a.existingEnv["EVE_CLIENT_SECRET"]; ok && a.clientSecret == "" {
		// The value is not kept (it is a secret); the review
		// shows it as already present and a blank answer keeps it.
		a.orgClientSecret = orgPresent
	}
	if v, ok := a.existingEnv["ESI_CONTACT"]; ok && a.contact == "" {
		a.contact = v
		a.orgContact = orgPresent
	}
	if v, ok := a.existingEnv["EVE_CALLBACK_URL"]; ok && a.callback == "" {
		a.callback = v
		a.orgCallback = orgPresent
	}
	if _, ok := a.existingEnv["DATABASE_URL"]; ok && a.databaseURL == "" {
		a.dbLocal = false
		a.databaseURL = "present"
		a.orgDB = orgPresent
	}
}

// templateDatabaseURL is the placeholder in .env.example.
const templateDatabaseURL = "postgres://evesynapse@localhost:5432/evesynapse?sslmode=disable"

// detectedLines reads out what this machine already has, for the
// review screen: values the installer found, not asked for.
func (a *answers) detectedLines() [][2]string {
	pg := "no"
	if a.hasLocalPG {
		pg = "yes, PostgreSQL is installed"
	}
	env := "no"
	if a.existingEnvAt != "" {
		env = "yes (" + a.existingEnvAt + ")"
	}
	return [][2]string{
		{"Architecture", a.arch + " (" + platformName() + ")"},
		{"Install directory", a.installDir},
		{"Local PostgreSQL", pg},
		{"Existing settings", env},
	}
}

// reviewRow is one row of the settings review.
type reviewRow struct {
	key     string // the .env key; "" for the install source
	setting string
	value   string
	source  origin
	group   string
	help    string
	edit    string // "source" or "db" for a row with its own screen
	isSet   bool   // has a value, not just the app's default
}

// fieldValue returns the prompt-backed value of a key, when it has one.
func (a *answers) fieldValue(key string) (string, bool) {
	switch key {
	case "EVE_CLIENT_ID":
		return a.clientID, true
	case "EVE_CLIENT_SECRET":
		return a.clientSecret, true
	case "ESI_CONTACT":
		return a.contact, true
	case "EVE_CALLBACK_URL":
		return a.callback, true
	}
	return "", false
}

// pending returns the value this run will write for key, if any. An
// empty value with ok true means the key is being cleared.
func (a *answers) pending(key string) (string, bool) {
	if v, ok := a.edits[key]; ok {
		return v, true
	}
	if v, isField := a.fieldValue(key); isField && v != "" && v != a.existingEnv[key] {
		return v, true
	}
	return "", false
}

// setValue records a change from the review screen.
func (a *answers) setValue(key, v string) {
	switch key {
	case "EVE_CLIENT_ID":
		a.clientID, a.orgClientID = v, orgNew
	case "EVE_CLIENT_SECRET":
		a.clientSecret, a.orgClientSecret = v, orgNew
	case "ESI_CONTACT":
		a.contact, a.orgContact = v, orgNew
	case "EVE_CALLBACK_URL":
		a.callback, a.orgCallback = v, orgNew
	}
	if v == "" && a.existingEnv[key] == "" {
		delete(a.edits, key) // clearing something unset changes nothing
		return
	}
	a.edits[key] = v
}

// undoValue drops this run's change to key.
func (a *answers) undoValue(key string) {
	delete(a.edits, key)
	existing := a.existingEnv[key]
	if isSecretKey(key) {
		existing = ""
	}
	org := orgNew
	if a.existingEnv[key] != "" {
		org = orgPresent
	}
	switch key {
	case "EVE_CLIENT_ID":
		a.clientID, a.orgClientID = existing, org
	case "EVE_CLIENT_SECRET":
		a.clientSecret, a.orgClientSecret = existing, org
	case "ESI_CONTACT":
		a.contact, a.orgContact = existing, org
	case "EVE_CALLBACK_URL":
		a.callback, a.orgCallback = existing, org
	}
}

// finalEdits is what gets written to .env after setup.sh has run.
func (a *answers) finalEdits() map[string]string {
	out := map[string]string{}
	for _, s := range settingsCatalog {
		if s.Key == "DATABASE_URL" {
			continue
		}
		if v, ok := a.pending(s.Key); ok {
			out[s.Key] = v
		}
	}
	if !a.dbLocal && a.databaseURL != "" && a.databaseURL != "present" {
		out["DATABASE_URL"] = a.databaseURL
	}
	return out
}

// effective is the value a key will have after the install. A kept
// secret reads as "present".
func (a *answers) effective(key string) string {
	if v, ok := a.pending(key); ok {
		return v
	}
	return a.existingEnv[key]
}

// reviewRows lists the install source and every setting in display
// order, secrets masked. With all false, only the important settings
// and anything that has a value are listed.
func (a *answers) reviewRows(all bool) []reviewRow {
	var rows []reviewRow
	if a.source == sourceBuild {
		rows = append(rows, reviewRow{setting: "Install source", value: "Build from source: " + a.sourceDir, source: a.orgSourceDir, group: "Install", help: "Where the program comes from.", edit: "source", isSet: true})
	} else {
		v := "Download the latest release"
		if a.release != nil {
			v += " (v" + a.release.Version + " from " + providerDisplayName(a.release.Provider) + ")"
		} else {
			v += " (not fetched yet)"
		}
		rows = append(rows, reviewRow{setting: "Install source", value: v, source: orgNew, group: "Install", help: "Where the program comes from.", edit: "source", isSet: true})
	}
	for _, group := range settingGroups {
		for _, s := range settingsCatalog {
			if s.Group != group {
				continue
			}
			r := a.settingRow(s)
			if all || s.Important || r.isSet {
				rows = append(rows, r)
			}
		}
	}
	return rows
}

// settingRow builds the review row of one setting.
func (a *answers) settingRow(s setting) reviewRow {
	r := reviewRow{key: s.Key, setting: s.Key, group: s.Group, help: s.Help}
	if s.Key == "DATABASE_URL" {
		r.edit, r.isSet = "db", true
		switch {
		case a.dbLocal:
			r.value, r.source = "PostgreSQL on this machine (set up by the installer)", orgNew
			if a.hasLocalPG {
				r.source = orgDetected
			}
		case a.databaseURL == "present":
			r.value, r.source = "Already set in "+a.existingEnvAt, orgPresent
		case a.databaseURL == "":
			r.value, r.source, r.isSet = "(blank: the app will not start without one)", orgSkipped, false
		default:
			r.value, r.source = maskDBURL(a.databaseURL), orgNew
		}
		return r
	}
	if v, ok := a.pending(s.Key); ok {
		if v == "" {
			r.value, r.source = "(will be cleared)", orgSkipped
			return r
		}
		r.value, r.source, r.isSet = v, orgNew, true
		if s.Kind == kindSecret {
			r.value = maskSecret(v)
		}
		return r
	}
	if v := a.existingEnv[s.Key]; v != "" {
		r.source, r.isSet = orgPresent, true
		r.value = v
		if s.Kind == kindSecret {
			r.value = "(set, hidden)"
		}
		return r
	}
	if s.Key == "TOKEN_ENCRYPTION_KEY" && a.existingEnvAt == "" {
		r.value, r.source, r.isSet = "(generated by the installer)", orgGenerated, true
		return r
	}
	r.source = orgDefault
	if s.Default != "" {
		r.value = s.Default
	} else {
		r.value = "(not set)"
	}
	return r
}

// reviewProblems checks the settings as a whole. Blockers would stop
// the app from starting; warnings are worth reading but legitimate.
func (a *answers) reviewProblems() (blockers, warnings []string) {
	if !a.dbLocal && a.databaseURL == "" {
		if isLinux() {
			blockers = append(blockers, "DATABASE_URL is needed for a database you already have.")
		} else {
			warnings = append(warnings, "No DATABASE_URL yet: the app will not start until you add one.")
		}
	}
	if sc := a.effective("SHARED_CACHE"); sc != "" && sc != "off" && a.effective("SHARED_CACHE_SECRET") == "" {
		blockers = append(blockers, "SHARED_CACHE is on but SHARED_CACHE_SECRET is empty, and the app refuses to start that way.")
	}
	switch a.effective("TOKEN_KEY_PROVIDER") {
	case "env":
		if a.effective("TOKEN_ENCRYPTION_KEY") == "" && a.existingEnvAt != "" {
			blockers = append(blockers, "TOKEN_KEY_PROVIDER is env but TOKEN_ENCRYPTION_KEY is empty.")
		}
	case "http":
		if a.effective("TOKEN_KEY_WRAPPED") == "" || a.effective("TOKEN_KEY_UNWRAP_URL") == "" {
			blockers = append(blockers, "TOKEN_KEY_PROVIDER is http but TOKEN_KEY_WRAPPED or TOKEN_KEY_UNWRAP_URL is empty.")
		}
	case "oci":
		if a.effective("TOKEN_KEY_WRAPPED") == "" || a.effective("TOKEN_KEY_OCI_KEY_ID") == "" || a.effective("TOKEN_KEY_OCI_CRYPTO_ENDPOINT") == "" {
			blockers = append(blockers, "TOKEN_KEY_PROVIDER is oci but its wrapped key, key ID or crypto endpoint is empty.")
		}
	case "none":
		warnings = append(warnings, "EVE login tokens will be stored unencrypted.")
	}
	if a.effective("EVE_CLIENT_ID") == "" || a.effective("EVE_CLIENT_SECRET") == "" {
		warnings = append(warnings, "Sign-in stays off until the EVE client ID and secret are set.")
	}
	if cb := a.effective("EVE_CALLBACK_URL"); cb == "" || strings.Contains(cb, "localhost") || strings.Contains(cb, "127.0.0.1") {
		warnings = append(warnings, "EVE_CALLBACK_URL points at this machine, so sign-in only works from here.")
	} else if strings.HasPrefix(cb, "http://") {
		warnings = append(warnings, "EVE_CALLBACK_URL is plain http, so sign-in cookies travel unencrypted.")
	}
	if host, _, err := net.SplitHostPort(a.listenAddr()); err == nil && host != "127.0.0.1" && host != "localhost" && host != "::1" {
		warnings = append(warnings, "ADDR accepts connections from other machines. Use 127.0.0.1:8080 behind a proxy.")
	}
	if a.effective("DEV_LOGIN") != "" {
		warnings = append(warnings, "DEV_LOGIN allows fake sign-ins. Never use it in production.")
	}
	return blockers, warnings
}

