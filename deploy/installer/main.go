// Command installer is the interactive front end for EveSynapse setup.
//
// It asks the operator for the settings the app needs, shows a review
// screen where every value can be changed, and then installs it:
// the embedded deploy/setup.sh does the binary, database, settings
// and service on Linux. The app listens on 127.0.0.1:8080; the
// operator arranges their own reverse proxy (Ferron, Caddy, nginx,
// or Cloudflare Tunnel) to reach it from the internet. The bolt
// turns in 3D above the prompts, sized to fit the terminal.
//
// Usage:
//
//	sudo ./installer            run the prompts and install
//	sudo ./installer --dry-run  run the prompts and review, then stop
//	                            before installing
//	sudo ./installer --source=download
//	                            skip the prompts that are answered
//
// When stdout is not a terminal, the prompts are plain questions on
// stdin/stdout instead of the full-screen interface.
//
// Every prompt is also settable by environment variable, so a
// scripted install still works with no prompts:
//
//	EVESYNAPSE_SOURCE=build|download   EVESYNAPSE_SOURCE_DIR=/path/to/checkout
//	EVESYNAPSE_DATABASE_URL=postgres://...
//	EVESYNAPSE_EVE_CLIENT_ID=...       EVESYNAPSE_EVE_CLIENT_SECRET=...
//	EVESYNAPSE_EVE_CALLBACK_URL=...    EVESYNAPSE_ESI_CONTACT=...
//
// A flag wins over the matching variable.
package main

import (
	"flag"
	"fmt"
	"net"
	"os"
	"path/filepath"
	"strings"
)

