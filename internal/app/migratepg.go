package app

// -migrate-pg: the one-time move of an existing SQLite-era
// database into Postgres (the v0.3.26 cutover). It opens the
// SQLite file read-only (never written, so rollback stays the
// previous binary + the old .env), creates/verifies the Postgres
// schema through the usual openDB path, copies every table in
// foreign-key-safe order, rewinds the identity sequences past
// the copied ids, and verifies per-table row counts plus a
// characters refresh-token spot check before it reports.
// Sessions are deliberately not migrated: everyone signs in once
// after the swap. Running it into a target that already holds
// rows is refused unless -force is given, in which case the
// target's tables are truncated first and re-copied.

