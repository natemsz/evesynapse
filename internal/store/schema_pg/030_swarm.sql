-- Schema step 030: the shared cache across instances (the
-- paper's "shared cache across instances" section).
--
-- Self-hosted instances share public ESI data (market history,
-- type names, corporation and alliance records) so the network
-- asks ESI for each record once instead of once per instance.
-- Private data (character snapshots, tokens, accounts) never
-- leaves the instance: no table here references it.
--
-- Trust is cryptographic and reputational. Every shared entry is
-- signed by the instance that fetched it; the signature is
-- verified before anything is stored, and entries are
-- spot-checked against ESI itself. A bad signature rejects the
-- entry outright; a failed spot check discards it and counts
-- against its signer. Trust below the floor excludes the signer
-- automatically; the operator can always exclude one by hand.
--
-- swarm_identity is this instance: one row, created on first
-- enable. The Ed25519 seed is sealed under a key derived from
-- the operator's shared secret (HKDF, like the token box), so a
-- copy of the database alone cannot sign as this instance. If
-- the secret changes, the seal stops opening and the instance
-- mints a fresh identity rather than reusing a key it cannot
-- read.
--
-- swarm_peers is every other instance this one has heard of, by
-- gossip, by seed, or by hand. gossip-learned rows wait for
-- approval in allowlist mode; excluded rows are never read from.
-- good_checks and bad_checks are the reputation ledger the
-- trust score is computed from (never reset by gossip).

CREATE TABLE IF NOT EXISTS swarm_identity (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    instance_id TEXT NOT NULL UNIQUE,
    public_key  TEXT NOT NULL,
    sealed_seed TEXT NOT NULL,
    created_at  timestamptz NOT NULL
);

CREATE TABLE IF NOT EXISTS swarm_peers (
    instance_id  TEXT PRIMARY KEY,
    base_url     TEXT NOT NULL,
    public_key   TEXT NOT NULL,
    source       TEXT NOT NULL DEFAULT 'gossip',
    approved     BOOLEAN NOT NULL DEFAULT FALSE,
    excluded     BOOLEAN NOT NULL DEFAULT FALSE,
    exclude_note TEXT NOT NULL DEFAULT '',
    good_checks  BIGINT NOT NULL DEFAULT 0,
    bad_checks   BIGINT NOT NULL DEFAULT 0,
    first_seen   timestamptz NOT NULL,
    last_seen    timestamptz NOT NULL,
    last_gossip  timestamptz
);

CREATE INDEX IF NOT EXISTS swarm_peers_seen ON swarm_peers (last_seen);

-- swarm_staging holds entries pulled from peers that verified
-- (signature good, payload decodes) but are waiting on a
-- spot check before they may be applied to the real tables.
-- Nothing is ever served from staging: renders read the real
-- tables only. An entry applies at most once; a newer fetch of
-- the same key replaces it.
CREATE TABLE IF NOT EXISTS swarm_staging (
    kind        TEXT NOT NULL,
    key         TEXT NOT NULL,
    payload     TEXT NOT NULL,
    signer      TEXT NOT NULL,
    signature   TEXT NOT NULL,
    fetched_at  timestamptz NOT NULL,
    received_at timestamptz NOT NULL,
    checked_at  timestamptz,
    PRIMARY KEY (kind, key)
);

CREATE INDEX IF NOT EXISTS swarm_staging_unchecked ON swarm_staging (received_at) WHERE checked_at IS NULL;

-- swarm_counters is the Sync page's record: entries applied per
-- kind, ESI calls saved, spot checks run and failed, all since
-- the counters were last reset (a row per name).
CREATE TABLE IF NOT EXISTS swarm_counters (
    name  TEXT PRIMARY KEY,
    value BIGINT NOT NULL DEFAULT 0
);
