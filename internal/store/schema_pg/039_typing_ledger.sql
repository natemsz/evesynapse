-- Schema step 039: the typing-guess ledger keeps its history.
--
-- typing_guesses held one row per (box, kind, entity, region),
-- and each keystroke deleted every row its box had: the guesses
-- still waiting, and the ones the pilot had opened. The hit
-- rates read over a seven-day window (the Sync page, and the
-- order the drains serve guesses in) therefore only ever saw
-- each box's last keystroke.
--
-- A guess is now a row that stays. superseded_at is set when a
-- later keystroke in the same box stops guessing it; a row with
-- superseded_at NULL is one of the box's current guesses, and a
-- box has at most one current row per entity. Whether it was
-- opened (hit_at) is never touched again, so the window fills
-- up. Rows are pruned by age (worker_typing.go).
--
-- (Numbered 039 to stay clear of the swarm steps 034-038, which
-- are in review; steps are independent and apply in any order.)

ALTER TABLE typing_guesses ADD COLUMN IF NOT EXISTS id BIGINT GENERATED BY DEFAULT AS IDENTITY;
ALTER TABLE typing_guesses ADD COLUMN IF NOT EXISTS superseded_at timestamptz;
ALTER TABLE typing_guesses DROP CONSTRAINT IF EXISTS typing_guesses_pkey;
ALTER TABLE typing_guesses ADD PRIMARY KEY (id);
CREATE UNIQUE INDEX IF NOT EXISTS typing_guesses_current
    ON typing_guesses (box, kind, entity_id, region_id) WHERE superseded_at IS NULL;
CREATE INDEX IF NOT EXISTS typing_guesses_noted ON typing_guesses (noted_at);
CREATE INDEX IF NOT EXISTS typing_guesses_entity ON typing_guesses (kind, entity_id, region_id, noted_at);
