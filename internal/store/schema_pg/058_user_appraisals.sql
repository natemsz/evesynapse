-- Schema step 058: saved appraisals for the appraisal tool.
--
-- One row per appraisal a signed-in user runs: the raw paste
-- (kept so re-pricing the same list later is an explicit new
-- appraisal, never a mutation of this one), a hash of it, the
-- priced snapshot exactly as it was shown (per-line price,
-- tier and as-of, totals and coverage, the lines that could
-- not be priced and why), and a share token for the read-only
-- public view of the snapshot. Anonymous appraisals are never
-- stored; they render from the same snapshot shape in memory.

CREATE TABLE IF NOT EXISTS user_appraisals (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    created_at   TIMESTAMPTZ NOT NULL DEFAULT now(),
    input_text   TEXT NOT NULL DEFAULT '',
    input_hash   TEXT NOT NULL DEFAULT '',
    share_token  TEXT NOT NULL DEFAULT '',
    snapshot     JSONB NOT NULL DEFAULT '{}'::jsonb,
    total_value  DOUBLE PRECISION NOT NULL DEFAULT 0,
    priced_lines BIGINT NOT NULL DEFAULT 0,
    total_lines  BIGINT NOT NULL DEFAULT 0
);

CREATE UNIQUE INDEX IF NOT EXISTS user_appraisals_share_token_idx
    ON user_appraisals (share_token);
CREATE INDEX IF NOT EXISTS user_appraisals_user_idx
    ON user_appraisals (user_id, id DESC);
