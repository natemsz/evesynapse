-- Intel channels (schema 078): shared streams of intel reports --
-- "hostiles in X" -- that the map draws as a layer for everyone who
-- can read them (internal/app/channels.go).
--
-- A channel belongs to the account that made it; only that account
-- manages it. Access is by grant: to one character, a corporation,
-- an alliance, or a director-kept group (org_groups), each read-only
-- or read and post. A reader's account matches a grant through any
-- of its linked characters.
--
-- A report is one sighting: the system, what was seen (text, the
-- pilots named, a hostile count when one was given), whether it was
-- a "clear", how it came in (the web form, pasted chat lines, an
-- attached scan) and when it was seen. Reports are kept 7 days.
CREATE TABLE IF NOT EXISTS intel_channels (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_user_id BIGINT NOT NULL,
    name          TEXT NOT NULL,
    description   TEXT NOT NULL DEFAULT '',
    created_at    TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS intel_channels_owner_idx ON intel_channels (owner_user_id);

CREATE TABLE IF NOT EXISTS intel_channel_grants (
    channel_id  BIGINT NOT NULL REFERENCES intel_channels (id) ON DELETE CASCADE,
    kind        TEXT NOT NULL CHECK (kind IN ('character', 'corporation', 'alliance', 'group')),
    target_id   BIGINT NOT NULL,
    can_post    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (channel_id, kind, target_id)
);
CREATE INDEX IF NOT EXISTS intel_channel_grants_target_idx ON intel_channel_grants (kind, target_id);

CREATE TABLE IF NOT EXISTS intel_reports (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id          BIGINT NOT NULL REFERENCES intel_channels (id) ON DELETE CASCADE,
    system_id           BIGINT NOT NULL,
    author_user_id      BIGINT NOT NULL DEFAULT 0,
    author_character_id BIGINT NOT NULL DEFAULT 0,
    -- reporter is who said it: the poster's character, or the
    -- speaker of a pasted chat line.
    reporter            TEXT NOT NULL DEFAULT '',
    text                TEXT NOT NULL DEFAULT '',
    pilots              TEXT NOT NULL DEFAULT '',
    hostiles            INTEGER NOT NULL DEFAULT 0,
    clear               BOOLEAN NOT NULL DEFAULT FALSE,
    scan_id             TEXT NOT NULL DEFAULT '',
    source              TEXT NOT NULL,
    seen_at             TIMESTAMPTZ NOT NULL,
    created_at          TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS intel_reports_channel_idx ON intel_reports (channel_id, id DESC);
CREATE INDEX IF NOT EXISTS intel_reports_seen_idx ON intel_reports (seen_at);
