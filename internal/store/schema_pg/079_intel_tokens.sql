-- Intel posting tokens (schema 079): what the desktop log watcher
-- (intelwatch, github.com/natemsz/intelwatch) signs its requests
-- with. A token is an account's,
-- made and revoked on the site, shown once; only its SHA-256 is kept,
-- with the first characters (prefix) to tell tokens apart. A request
-- bearing one acts as that account, for the intel channel API only:
-- listing the channels it may post to, and posting chat lines.
CREATE TABLE IF NOT EXISTS intel_tokens (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id      BIGINT NOT NULL,
    name         TEXT NOT NULL,
    prefix       TEXT NOT NULL,
    token_hash   TEXT NOT NULL UNIQUE,
    created_at   TIMESTAMPTZ NOT NULL,
    last_used_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS intel_tokens_user_idx ON intel_tokens (user_id);
