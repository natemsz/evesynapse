-- Axon pairing (schema 081): one-time pairing codes and per-device
-- request signing. A player makes a short-lived code on the site and
-- enters it in Axon; Axon exchanges it (with its new Ed25519 public
-- key) for a posting token bound to that key. Only requests signed
-- by the matching private key are accepted, so a copied token alone
-- is useless. Tokens from before pairing have no key and stop here:
-- their owners pair again.
ALTER TABLE intel_tokens ADD COLUMN IF NOT EXISTS public_key TEXT NOT NULL DEFAULT '';
ALTER TABLE intel_tokens ADD COLUMN IF NOT EXISTS device TEXT NOT NULL DEFAULT '';

CREATE TABLE IF NOT EXISTS intel_pairing_codes (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL,
    name       TEXT NOT NULL,
    code_hash  TEXT NOT NULL UNIQUE,
    created_at TIMESTAMPTZ NOT NULL,
    expires_at TIMESTAMPTZ NOT NULL,
    used_at    TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS intel_pairing_codes_user_idx ON intel_pairing_codes (user_id);
