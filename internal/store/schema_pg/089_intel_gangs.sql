-- Tracked gangs (schema 089): the fusion layer over report
-- groups (schema 087). A gang is one body of pilots tracked
-- across the groups that sight it: groups are per channel and
-- system, so a gang that jumps a gate or is reported again
-- after its group's window closes founds a new group, and the
-- gang is what says the two sightings are the same people.
-- Identity is decided at ingest from pilot overlap, time and
-- jump distance (internal/app/intel_gangs.go); renders read
-- these rows only. A gang with no sighting for the gang
-- lifetime is closed and never matched again: a later sighting
-- of the same pilots founds a new gang.
CREATE TABLE IF NOT EXISTS intel_gangs (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    channel_id     BIGINT NOT NULL,
    first_seen_at  TIMESTAMPTZ NOT NULL,
    last_seen_at   TIMESTAMPTZ NOT NULL,
    last_system_id BIGINT NOT NULL DEFAULT 0,
    sightings      INTEGER NOT NULL DEFAULT 0,
    strength       DOUBLE PRECISION NOT NULL DEFAULT 0,
    closed_at      TIMESTAMPTZ,
    snapshot       TEXT NOT NULL DEFAULT ''
);
CREATE INDEX IF NOT EXISTS intel_gangs_channel_open_idx ON intel_gangs (channel_id, closed_at, last_seen_at DESC);

-- Which groups currently belong to a gang. A group stands in
-- at most one gang at a time; the assignment is rewritten
-- whenever fusion re-evaluates the group, so the table is the
-- current picture, not a history.
CREATE TABLE IF NOT EXISTS intel_gang_groups (
    gang_id  BIGINT NOT NULL,
    group_id BIGINT NOT NULL,
    PRIMARY KEY (gang_id, group_id)
);
CREATE INDEX IF NOT EXISTS intel_gang_groups_group_idx ON intel_gang_groups (group_id);
