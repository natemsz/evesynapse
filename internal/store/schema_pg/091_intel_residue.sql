-- The residue step's store (schema 091, internal/app/residue_model.go):
-- what a settled reading's leftover spans produced. intel_residue_calls
-- logs every completed pass whole, the spans offered and the raw reply,
-- as the raw material the label corpus is later built from.
-- intel_residue_notes is the pass's stored reading of a span: either a
-- link to an entity the reading itself already resolved (entity_id set,
-- unconfirmed false), or something new read in the span, which stands
-- flagged unconfirmed and is never read back as a resolved entity
-- anywhere. Deterministic facts stay in intel_reports.analysis; this
-- step never rewrites them.
CREATE TABLE IF NOT EXISTS intel_residue_calls (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id  BIGINT NOT NULL,
    spans      TEXT NOT NULL DEFAULT '',
    output     TEXT NOT NULL DEFAULT '',
    created_at TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS intel_residue_calls_report_idx ON intel_residue_calls (report_id, created_at DESC);

CREATE TABLE IF NOT EXISTS intel_residue_notes (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    report_id   BIGINT NOT NULL,
    call_id     BIGINT NOT NULL DEFAULT 0,
    span        TEXT NOT NULL DEFAULT '',
    kind        TEXT NOT NULL DEFAULT '',
    entity_id   BIGINT NOT NULL DEFAULT 0,
    entity_name TEXT NOT NULL DEFAULT '',
    n           INTEGER NOT NULL DEFAULT 0,
    unconfirmed BOOLEAN NOT NULL DEFAULT TRUE,
    created_at  TIMESTAMPTZ NOT NULL
);
CREATE INDEX IF NOT EXISTS intel_residue_notes_report_idx ON intel_residue_notes (report_id, created_at, id);
