-- Global notices (schema 107, internal/app/notices.go): what an
-- administrator posts to every visitor. A service announcement, an
-- in-game promotion or giveaway, a security warning. Each shows as a
-- banner on every page until it ends, is retired, or the visitor
-- dismisses it.
--
-- body_html is the detail post as the server rendered and sanitized
-- it at save time; it is the only form of the post a page ever shows.
-- body_md is kept so the post can be edited again.
--
-- created_by and the audit rows carry no foreign key on purpose: the
-- record of who said what outlives the account that said it.
CREATE TABLE IF NOT EXISTS global_notices (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title          TEXT NOT NULL CHECK (char_length(title) BETWEEN 1 AND 120),
    severity       TEXT NOT NULL CHECK (severity IN ('info', 'promo', 'warning', 'critical')),
    body_md        TEXT NOT NULL DEFAULT '' CHECK (char_length(body_md) <= 8000),
    body_html      TEXT NOT NULL DEFAULT '',
    urgent         BOOLEAN NOT NULL DEFAULT false,
    urgent_sent_at TIMESTAMPTZ,
    starts_at      TIMESTAMPTZ NOT NULL,
    ends_at        TIMESTAMPTZ NOT NULL,
    retired_at     TIMESTAMPTZ,
    created_by     BIGINT NOT NULL,
    created_at     TIMESTAMPTZ NOT NULL,
    updated_at     TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS global_notices_live_idx ON global_notices (ends_at) WHERE retired_at IS NULL;

-- A signed-in visitor's dismissals. Anonymous visitors keep theirs in
-- a browser cookie instead.
CREATE TABLE IF NOT EXISTS global_notice_dismissals (
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    notice_id    BIGINT NOT NULL REFERENCES global_notices (id) ON DELETE CASCADE,
    dismissed_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (user_id, notice_id)
);

-- Every publish, edit, retire and app-notification send, with the
-- content as it stood after the change. The publish rate limits
-- count these rows.
CREATE TABLE IF NOT EXISTS global_notice_audit (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    notice_id      BIGINT NOT NULL,
    action         TEXT NOT NULL CHECK (action IN ('publish', 'edit', 'retire', 'urgent')),
    user_id        BIGINT NOT NULL,
    character_id   BIGINT NOT NULL DEFAULT 0,
    character_name TEXT NOT NULL DEFAULT '',
    title          TEXT NOT NULL,
    severity       TEXT NOT NULL,
    body_md        TEXT NOT NULL DEFAULT '',
    ends_at        TIMESTAMPTZ NOT NULL,
    at             TIMESTAMPTZ NOT NULL
);

CREATE INDEX IF NOT EXISTS global_notice_audit_at_idx ON global_notice_audit (at DESC);
CREATE INDEX IF NOT EXISTS global_notice_audit_user_idx ON global_notice_audit (user_id, at DESC);
