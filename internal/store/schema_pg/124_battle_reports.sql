-- Schema step 124: battle reports.
--
-- Axon reads a pilot's game logs, cuts them into fights and posts
-- each fight's aggregate (POST /api/intel/v1/fights): its frame,
-- a per-second series and one tally per other party. The raw log
-- never reaches the site. Everything a report page shows is stored
-- here at ingest and when correlation runs, so the page reads rows:
--
--   * battle_fights, one row per fight: the frame, its totals, the
--     matched mails' counts and ISK, and the share link.
--   * battle_fight_series, the per-second series and the per-party
--     10-second slices as posted (JSON), and the chart geometry
--     derived from them and the matched kills.
--   * battle_fight_moments, the fight's timeline: each moment a
--     kind (kill, loss, tackle, energy, pressure, repairs, focus), a
--     window in seconds, a title, and the detail its panel shows
--     (JSON), all derived when the fight is correlated.
--   * battle_fight_parties, one row per other party. The log names
--     pilots as "Name[TICK](Hull)" and everything else bare; a bare
--     name that is a ship type (repairs, energy warfare and tackle
--     lines name ships by hull alone) is stored with that hull.
--   * battle_fight_weapons, each weapon's shots one way between the
--     pilot and a party, with its hit quality counts.
--   * battle_fight_tackles, the warp scramble and disruption
--     attempts the log saw on grid: the client logs every one in
--     view, not only those on the pilot, naming both ships by hull
--     ("you" for the pilot when it says so).
--   * battle_fight_kills, the killmails matched to the fight.
--   * battle_fight_findings, the rule engine's sentences.

CREATE TABLE IF NOT EXISTS battle_fights (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    character_id    BIGINT NOT NULL,
    listener        TEXT NOT NULL,
    session_file    TEXT NOT NULL DEFAULT '',
    started_at      TIMESTAMPTZ NOT NULL,
    ended_at        TIMESTAMPTZ NOT NULL,
    system_id       BIGINT NOT NULL DEFAULT 0,
    system_from     TEXT NOT NULL DEFAULT '',
    hull_type_id    BIGINT NOT NULL DEFAULT 0,
    hull_from       TEXT NOT NULL DEFAULT '',
    damage_out      BIGINT NOT NULL DEFAULT 0,
    damage_in       BIGINT NOT NULL DEFAULT 0,
    reps_out        BIGINT NOT NULL DEFAULT 0,
    reps_in         BIGINT NOT NULL DEFAULT 0,
    cap_in          BIGINT NOT NULL DEFAULT 0,
    peak_in_dps     BIGINT NOT NULL DEFAULT 0,
    peak_in_at      INTEGER NOT NULL DEFAULT 0,
    pilots          INTEGER NOT NULL DEFAULT 0,
    kills           INTEGER NOT NULL DEFAULT 0,
    losses          INTEGER NOT NULL DEFAULT 0,
    isk_destroyed   DOUBLE PRECISION NOT NULL DEFAULT 0,
    isk_lost        DOUBLE PRECISION NOT NULL DEFAULT 0,
    outcome         TEXT NOT NULL DEFAULT 'nokill',
    spark_out       TEXT NOT NULL DEFAULT '',
    spark_in        TEXT NOT NULL DEFAULT '',
    lines           INTEGER NOT NULL DEFAULT 0,
    unparsed        INTEGER NOT NULL DEFAULT 0,
    share_token     TEXT NOT NULL,
    shared          BOOLEAN NOT NULL DEFAULT FALSE,
    received_at     TIMESTAMPTZ NOT NULL,
    correlated_at   TIMESTAMPTZ,
    UNIQUE (character_id, started_at),
    UNIQUE (share_token)
);
CREATE INDEX IF NOT EXISTS battle_fights_user_idx ON battle_fights (user_id, started_at DESC);
CREATE INDEX IF NOT EXISTS battle_fights_char_idx ON battle_fights (character_id, started_at DESC);
CREATE INDEX IF NOT EXISTS battle_fights_recent_idx ON battle_fights (ended_at DESC);

CREATE TABLE IF NOT EXISTS battle_fight_series (
    fight_id  BIGINT PRIMARY KEY REFERENCES battle_fights (id) ON DELETE CASCADE,
    series    TEXT NOT NULL,
    slices    TEXT NOT NULL DEFAULT '',
    chart     TEXT NOT NULL DEFAULT ''
);

CREATE TABLE IF NOT EXISTS battle_fight_moments (
    fight_id   BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    seq        INTEGER NOT NULL,
    kind       TEXT NOT NULL,
    at_second  INTEGER NOT NULL,
    end_second INTEGER NOT NULL,
    title      TEXT NOT NULL,
    detail     TEXT NOT NULL,
    PRIMARY KEY (fight_id, seq)
);

CREATE TABLE IF NOT EXISTS battle_fight_parties (
    fight_id         BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    seq              INTEGER NOT NULL,
    name             TEXT NOT NULL,
    ticker           TEXT NOT NULL DEFAULT '',
    hull             TEXT NOT NULL DEFAULT '',
    hull_type_id     BIGINT NOT NULL DEFAULT 0,
    pilot            BOOLEAN NOT NULL DEFAULT FALSE,
    character_id     BIGINT NOT NULL DEFAULT 0,
    damage_out       BIGINT NOT NULL DEFAULT 0,
    damage_in        BIGINT NOT NULL DEFAULT 0,
    reps_out         BIGINT NOT NULL DEFAULT 0,
    reps_in          BIGINT NOT NULL DEFAULT 0,
    cap_out          BIGINT NOT NULL DEFAULT 0,
    cap_in           BIGINT NOT NULL DEFAULT 0,
    first_at         TIMESTAMPTZ NOT NULL,
    last_at          TIMESTAMPTZ NOT NULL,
    died             BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (fight_id, seq)
);

CREATE TABLE IF NOT EXISTS battle_fight_weapons (
    fight_id       BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    party_seq      INTEGER NOT NULL,
    dir            TEXT NOT NULL,
    weapon         TEXT NOT NULL,
    weapon_type_id BIGINT NOT NULL DEFAULT 0,
    shots          BIGINT NOT NULL DEFAULT 0,
    damage         BIGINT NOT NULL DEFAULT 0,
    q_miss         BIGINT NOT NULL DEFAULT 0,
    q_graze        BIGINT NOT NULL DEFAULT 0,
    q_glance       BIGINT NOT NULL DEFAULT 0,
    q_hit          BIGINT NOT NULL DEFAULT 0,
    q_penetrate    BIGINT NOT NULL DEFAULT 0,
    q_smash        BIGINT NOT NULL DEFAULT 0,
    q_wreck        BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (fight_id, party_seq, dir, weapon)
);

CREATE TABLE IF NOT EXISTS battle_fight_tackles (
    fight_id  BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    seq       INTEGER NOT NULL,
    from_name TEXT NOT NULL,
    to_name   TEXT NOT NULL,
    kind      TEXT NOT NULL,
    first_at  TIMESTAMPTZ NOT NULL,
    attempts  BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (fight_id, seq)
);

CREATE TABLE IF NOT EXISTS battle_fight_kills (
    fight_id            BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    killmail_id         BIGINT NOT NULL,
    killmail_time       TIMESTAMPTZ NOT NULL,
    at_second           INTEGER NOT NULL,
    loss                BOOLEAN NOT NULL,
    victim_character_id BIGINT NOT NULL DEFAULT 0,
    victim_name         TEXT NOT NULL DEFAULT '',
    ship_type_id        BIGINT NOT NULL DEFAULT 0,
    damage_taken        BIGINT NOT NULL DEFAULT 0,
    my_damage           BIGINT NOT NULL DEFAULT 0,
    ttk_seconds         INTEGER NOT NULL DEFAULT -1,
    value_isk           DOUBLE PRECISION,
    PRIMARY KEY (fight_id, killmail_id)
);
CREATE INDEX IF NOT EXISTS battle_fight_kills_mail_idx ON battle_fight_kills (killmail_id);

CREATE TABLE IF NOT EXISTS battle_fight_findings (
    fight_id BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    seq      INTEGER NOT NULL,
    rule     TEXT NOT NULL,
    text     TEXT NOT NULL,
    PRIMARY KEY (fight_id, seq)
);
