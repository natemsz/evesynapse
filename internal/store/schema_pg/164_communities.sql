-- Schema step 164: communities and verified pilots.
--
-- A community is a group of players outside the game's corporations.
-- It owns things the way a corporation or alliance does, and its groups
-- are ordinary org_groups rows.
--
-- verified_pilots holds one row for each character with a community
-- identity: a pilot who proved who they are through EVE sign-in without
-- making an account, or an account's character that joined a community.
-- Its owner_hash is the baseline that shows a character has been sold.
-- No token is stored here.

CREATE TABLE IF NOT EXISTS communities (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    slug                 TEXT NOT NULL UNIQUE,
    name                 TEXT NOT NULL,
    description          TEXT NOT NULL DEFAULT '',
    join_policy          TEXT NOT NULL DEFAULT 'approval' CHECK (join_policy IN ('open', 'approval', 'invite')),
    listed               BOOLEAN NOT NULL DEFAULT FALSE,
    invite_token         TEXT UNIQUE,
    member_count         INTEGER NOT NULL DEFAULT 0,
    pending_count        INTEGER NOT NULL DEFAULT 0,
    created_by_character BIGINT NOT NULL,
    created_at           timestamptz NOT NULL DEFAULT now(),
    archived_at          timestamptz
);

-- Names are unique in the directory only, so naming a community never
-- reveals that a private one exists.
CREATE UNIQUE INDEX IF NOT EXISTS communities_listed_name ON communities (lower(name))
    WHERE listed AND archived_at IS NULL;
CREATE INDEX IF NOT EXISTS communities_directory ON communities (member_count DESC, lower(name), id)
    WHERE listed AND archived_at IS NULL;
CREATE INDEX IF NOT EXISTS communities_directory_search ON communities USING gin (name gin_trgm_ops)
    WHERE listed AND archived_at IS NULL;

CREATE TABLE IF NOT EXISTS community_members (
    community_id BIGINT NOT NULL REFERENCES communities (id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL,
    name         TEXT NOT NULL,
    role         TEXT NOT NULL DEFAULT 'member' CHECK (role IN ('leader', 'admin', 'member')),
    state        TEXT NOT NULL DEFAULT 'active' CHECK (state IN ('active', 'pending', 'banned')),
    joined_at    timestamptz NOT NULL DEFAULT now(),
    added_by     BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (community_id, character_id),
    CHECK (role = 'member' OR state = 'active')
);

CREATE UNIQUE INDEX IF NOT EXISTS community_one_leader ON community_members (community_id) WHERE role = 'leader';
CREATE INDEX IF NOT EXISTS community_members_character ON community_members (character_id, state);
CREATE INDEX IF NOT EXISTS community_members_list ON community_members (community_id, state, lower(name), character_id);
CREATE INDEX IF NOT EXISTS community_members_admins ON community_members (community_id, joined_at)
    WHERE role = 'admin' AND state = 'active';

CREATE TABLE IF NOT EXISTS verified_pilots (
    character_id   BIGINT PRIMARY KEY,
    name           TEXT NOT NULL,
    owner_hash     TEXT NOT NULL DEFAULT '',
    corporation_id BIGINT NOT NULL DEFAULT 0,
    alliance_id    BIGINT NOT NULL DEFAULT 0,
    affiliation_at timestamptz,
    verified_at    timestamptz NOT NULL DEFAULT now(),
    last_seen_at   timestamptz NOT NULL DEFAULT now()
);

ALTER TABLE org_groups DROP CONSTRAINT IF EXISTS org_groups_owner_kind_check;
ALTER TABLE org_groups ADD CONSTRAINT org_groups_owner_kind_check
    CHECK (owner_kind IN ('corporation', 'alliance', 'community'));

-- A group's size is stored, so a page of groups reads no member rows.
ALTER TABLE org_groups ADD COLUMN IF NOT EXISTS member_count INTEGER NOT NULL DEFAULT 0;
UPDATE org_groups g SET member_count = (SELECT count(*) FROM org_group_members m WHERE m.group_id = g.id);

CREATE OR REPLACE FUNCTION org_group_members_counted() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF TG_OP = 'INSERT' THEN
        UPDATE org_groups SET member_count = member_count + 1 WHERE id = NEW.group_id;
        RETURN NEW;
    END IF;
    UPDATE org_groups SET member_count = member_count - 1 WHERE id = OLD.group_id;
    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS org_group_members_counted ON org_group_members;
CREATE TRIGGER org_group_members_counted
AFTER INSERT OR DELETE ON org_group_members
FOR EACH ROW EXECUTE FUNCTION org_group_members_counted();

-- Every change to a membership keeps the community's stored counts
-- right, and a character that stops being an active member leaves the
-- community's groups, so coming back never restores a group place.
CREATE OR REPLACE FUNCTION community_members_changed() RETURNS trigger
LANGUAGE plpgsql AS $$
DECLARE
    was_active  BOOLEAN := TG_OP <> 'INSERT' AND OLD.state = 'active';
    is_active   BOOLEAN := TG_OP <> 'DELETE' AND NEW.state = 'active';
    was_pending BOOLEAN := TG_OP <> 'INSERT' AND OLD.state = 'pending';
    is_pending  BOOLEAN := TG_OP <> 'DELETE' AND NEW.state = 'pending';
    target      BIGINT;
BEGIN
    IF TG_OP = 'DELETE' THEN
        target := OLD.community_id;
    ELSE
        target := NEW.community_id;
    END IF;
    IF was_active <> is_active OR was_pending <> is_pending THEN
        UPDATE communities SET
            member_count  = member_count + is_active::int - was_active::int,
            pending_count = pending_count + is_pending::int - was_pending::int
        WHERE id = target;
    END IF;
    IF was_active AND NOT is_active THEN
        DELETE FROM org_group_members m
        USING org_groups g
        WHERE m.group_id = g.id
          AND g.owner_kind = 'community'
          AND g.owner_id = OLD.community_id
          AND m.character_id = OLD.character_id;
    END IF;
    IF TG_OP = 'DELETE' THEN
        RETURN OLD;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS community_members_changed ON community_members;
CREATE TRIGGER community_members_changed
AFTER INSERT OR UPDATE OR DELETE ON community_members
FOR EACH ROW EXECUTE FUNCTION community_members_changed();

-- Ends a character's community identity: when it is unlinked, removed
-- with its account, sold, or its pilot asks. Bans stay, so a ban cannot
-- be cleared by leaving. A community that loses its leader passes to
-- its longest-serving admin with a working account; with none, it
-- closes, because nobody is left who could run it.
CREATE OR REPLACE FUNCTION release_community_character(pilot BIGINT) RETURNS void
LANGUAGE plpgsql AS $$
DECLARE
    led   BIGINT[];
    owned BIGINT;
    heir  BIGINT;
BEGIN
    SELECT COALESCE(array_agg(community_id), '{}') INTO led
    FROM community_members
    WHERE character_id = pilot AND role = 'leader';

    DELETE FROM community_members WHERE character_id = pilot AND state <> 'banned';

    FOREACH owned IN ARRAY led LOOP
        SELECT m.character_id INTO heir
        FROM community_members m
        JOIN characters c ON c.character_id = m.character_id AND c.link_state = 'ok'
        JOIN verified_pilots v ON v.character_id = m.character_id
        WHERE m.community_id = owned AND m.role = 'admin' AND m.state = 'active'
          AND (v.owner_hash = '' OR c.owner_hash = '' OR v.owner_hash = c.owner_hash)
        ORDER BY m.joined_at, m.character_id
        LIMIT 1;
        IF FOUND THEN
            UPDATE community_members SET role = 'leader'
            WHERE community_id = owned AND character_id = heir;
        ELSE
            UPDATE communities SET archived_at = now()
            WHERE id = owned AND archived_at IS NULL;
        END IF;
    END LOOP;

    DELETE FROM verified_pilots WHERE character_id = pilot;
END;
$$;

-- Removing a stale link never touches the places of a newer owner: a
-- row whose owner differs from the verified one is not that identity.
CREATE OR REPLACE FUNCTION characters_release_community() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF EXISTS (
        SELECT 1 FROM verified_pilots v
        WHERE v.character_id = OLD.character_id
          AND v.owner_hash <> '' AND OLD.owner_hash <> '' AND v.owner_hash <> OLD.owner_hash
    ) THEN
        RETURN OLD;
    END IF;
    PERFORM release_community_character(OLD.character_id);
    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS characters_release_community ON characters;
CREATE TRIGGER characters_release_community
AFTER DELETE ON characters
FOR EACH ROW EXECUTE FUNCTION characters_release_community();
