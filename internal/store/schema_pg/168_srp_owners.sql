-- Schema step 168: ship replacement for corporations, alliances and
-- communities.
--
-- A policy is how an owner replaces ships: how a payout is worked out,
-- what a claim has to show, and who can read the ledger. A fleet can
-- name one; otherwise the owner's default applies. A request keeps the
-- policy and the suggested payout it was filed under, so changing a
-- policy later cannot change a claim already made.
--
-- killmail_id stays UNIQUE across every owner, and a request that was
-- ever answered cannot be withdrawn, so one loss can never be paid twice.
--
-- corporation_id and a NOT NULL user_id are what the previous release
-- reads. A request of another owner, or one with no account behind it,
-- stores corporation_id 0, so that release's corporation lists never
-- reach a row it cannot read.

CREATE TABLE IF NOT EXISTS srp_policies (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    owner_kind          TEXT NOT NULL CHECK (owner_kind IN ('corporation', 'alliance', 'community')),
    owner_id            BIGINT NOT NULL CHECK (owner_id > 0),
    name                TEXT NOT NULL CHECK (char_length(name) BETWEEN 1 AND 60),
    mode                TEXT NOT NULL DEFAULT 'manual'
                        CHECK (mode IN ('manual', 'percent_of_loss', 'fixed_by_hull')),
    percent             INTEGER NOT NULL DEFAULT 100 CHECK (percent BETWEEN 1 AND 100),
    max_payout          DOUBLE PRECISION NOT NULL DEFAULT 0 CHECK (max_payout >= 0),
    requires_doctrine   BOOLEAN NOT NULL DEFAULT FALSE,
    requires_attendance BOOLEAN NOT NULL DEFAULT FALSE,
    claim_window_hours  INTEGER NOT NULL DEFAULT 720 CHECK (claim_window_hours BETWEEN 1 AND 720),
    ledger_visibility   TEXT NOT NULL DEFAULT 'handlers'
                        CHECK (ledger_visibility IN ('handlers', 'members')),
    policy_text         TEXT NOT NULL DEFAULT '',
    is_default          BOOLEAN NOT NULL DEFAULT FALSE,
    updated_by          BIGINT NOT NULL DEFAULT 0,
    updated_at          timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS srp_policies_owner_name
    ON srp_policies (owner_kind, owner_id, lower(name));
CREATE UNIQUE INDEX IF NOT EXISTS srp_policies_one_default
    ON srp_policies (owner_kind, owner_id) WHERE is_default;

CREATE TABLE IF NOT EXISTS srp_policy_hulls (
    policy_id    BIGINT NOT NULL REFERENCES srp_policies (id) ON DELETE CASCADE,
    ship_type_id BIGINT NOT NULL,
    payout       DOUBLE PRECISION NOT NULL CHECK (payout >= 0),
    PRIMARY KEY (policy_id, ship_type_id)
);

-- A corporation's written policy becomes its default policy, with the
-- behavior it has today: the handler decides, and nothing is required.
INSERT INTO srp_policies (owner_kind, owner_id, name, policy_text, is_default, updated_at)
SELECT 'corporation', corporation_id, 'Standard', policy, TRUE, updated_at
FROM srp_settings
WHERE btrim(policy) <> '' AND corporation_id > 0
ON CONFLICT DO NOTHING;

ALTER TABLE ops
    ADD COLUMN IF NOT EXISTS srp_policy_id BIGINT REFERENCES srp_policies (id) ON DELETE SET NULL;

ALTER TABLE srp_requests
    ADD COLUMN IF NOT EXISTS owner_kind       TEXT NOT NULL DEFAULT 'corporation',
    ADD COLUMN IF NOT EXISTS owner_id         BIGINT NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS policy_id        BIGINT REFERENCES srp_policies (id) ON DELETE SET NULL,
    ADD COLUMN IF NOT EXISTS suggested_payout DOUBLE PRECISION NOT NULL DEFAULT 0,
    ADD COLUMN IF NOT EXISTS fit_evidence     TEXT NOT NULL DEFAULT '',
    ADD COLUMN IF NOT EXISTS answered_at      timestamptz,
    ADD COLUMN IF NOT EXISTS previous_payout  DOUBLE PRECISION NOT NULL DEFAULT 0;

UPDATE srp_requests SET
    owner_id         = corporation_id,
    suggested_payout = loss_value,
    answered_at      = handled_at
WHERE owner_kind = 'corporation' AND owner_id <> corporation_id;

-- Kept here so every release's writes follow them:
--  - a row written without an owner belongs to its corporation;
--  - a row with no account behind it leaves the corporation lists of the
--    previous release;
--  - the first answer is remembered, and a paid amount survives the
--    request being opened again;
--  - removing an account keeps the record of a claim, not what its owner
--    wrote on it.
CREATE OR REPLACE FUNCTION srp_requests_owner_columns() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    IF NEW.owner_kind = 'corporation' AND NEW.corporation_id <> 0 THEN
        NEW.owner_id := NEW.corporation_id;
    END IF;
    IF NEW.user_id IS NULL THEN
        NEW.corporation_id := 0;
    END IF;
    IF NEW.handled_at IS NOT NULL AND NEW.answered_at IS NULL THEN
        NEW.answered_at := NEW.handled_at;
    END IF;
    IF TG_OP = 'UPDATE' THEN
        IF OLD.user_id IS NOT NULL AND NEW.user_id IS NULL THEN
            NEW.note := '';
        END IF;
        IF OLD.status = 'paid' AND NEW.status <> 'paid' THEN
            NEW.previous_payout := OLD.payout;
        END IF;
    END IF;
    RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS srp_requests_owner_columns ON srp_requests;
CREATE TRIGGER srp_requests_owner_columns
BEFORE INSERT OR UPDATE OF owner_kind, owner_id, corporation_id, user_id, handled_at, status ON srp_requests
FOR EACH ROW EXECUTE FUNCTION srp_requests_owner_columns();

ALTER TABLE srp_requests DROP CONSTRAINT IF EXISTS srp_requests_owner_kind_check;
ALTER TABLE srp_requests ADD CONSTRAINT srp_requests_owner_kind_check
    CHECK (owner_kind IN ('corporation', 'alliance', 'community'));
ALTER TABLE srp_requests DROP CONSTRAINT IF EXISTS srp_requests_owner_matches_corporation;
ALTER TABLE srp_requests ADD CONSTRAINT srp_requests_owner_matches_corporation
    CHECK (owner_kind = 'corporation' OR (corporation_id = 0 AND owner_id > 0));

-- A pilot with no account can claim, and deleting an account keeps the
-- record of what was paid.
ALTER TABLE srp_requests ALTER COLUMN user_id DROP NOT NULL;
ALTER TABLE srp_requests DROP CONSTRAINT IF EXISTS srp_requests_user_id_fkey;
ALTER TABLE srp_requests ADD CONSTRAINT srp_requests_user_id_fkey
    FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL;

CREATE INDEX IF NOT EXISTS srp_requests_owner ON srp_requests (owner_kind, owner_id, status, created_at);
CREATE INDEX IF NOT EXISTS srp_requests_op ON srp_requests (op_id, created_at);
CREATE INDEX IF NOT EXISTS srp_requests_character ON srp_requests (character_id, created_at);
