-- Schema step 170: fleet battle reports, points and leaderboards.
--
-- The worker builds everything here once a fleet has closed, so pages
-- only read rows:
--
--   * op_battle_consent, the pilots who chose to add their battle logs
--     to one fleet's report. It names the account, so a character that
--     later changes hands never brings the old account's logs along.
--   * fleet_report_state, which fleets need building. dirty_seq takes a
--     new sequence value on each mark, so a build clears only the mark
--     it read and never a newer one.
--   * fleet_battles and its child tables, one row per battle of a fleet:
--     a roam can fight in several systems, so one fleet can hold several.
--   * fleet_score_pilots and fleet_score_mails, what each pilot earned
--     on a fleet. A mail is stored per pilot and fleet, and ranking
--     counts it once per pilot, so two fleets that overlap cannot score
--     the same kill twice.
--   * fleet_leaders, the ranked boards the public pages read.

-- first_fleet_at is when the fleet read first saw the pilot. A row marked
-- by hand and sighted later keeps its first_seen_at for ship replacement,
-- and a hand mark's time says nothing about when the pilot flew.
ALTER TABLE op_attendance ADD COLUMN IF NOT EXISTS first_fleet_at TIMESTAMPTZ;
UPDATE op_attendance SET first_fleet_at = first_seen_at
WHERE source = 'fleet' AND first_fleet_at IS NULL;

CREATE TABLE IF NOT EXISTS op_battle_consent (
    op_id        BIGINT NOT NULL REFERENCES ops (id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL,
    user_id      BIGINT NOT NULL REFERENCES users (id) ON DELETE CASCADE,
    consented_at TIMESTAMPTZ NOT NULL,
    PRIMARY KEY (op_id, character_id)
);
CREATE INDEX IF NOT EXISTS op_battle_consent_character ON op_battle_consent (character_id, op_id);
CREATE INDEX IF NOT EXISTS op_battle_consent_user ON op_battle_consent (user_id);

CREATE SEQUENCE IF NOT EXISTS fleet_report_seq;

CREATE TABLE IF NOT EXISTS fleet_report_state (
    op_id       BIGINT PRIMARY KEY REFERENCES ops (id) ON DELETE CASCADE,
    dirty_seq   BIGINT,
    computed_at TIMESTAMPTZ
);
CREATE INDEX IF NOT EXISTS fleet_report_state_dirty
    ON fleet_report_state (dirty_seq)
    WHERE dirty_seq IS NOT NULL;

CREATE TABLE IF NOT EXISTS fleet_battles (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    op_id            BIGINT NOT NULL REFERENCES ops (id) ON DELETE CASCADE,
    seq              INTEGER NOT NULL,
    system_id        BIGINT NOT NULL DEFAULT 0,
    started_at       TIMESTAMPTZ NOT NULL,
    ended_at         TIMESTAMPTZ NOT NULL,
    pilots_total     INTEGER NOT NULL DEFAULT 0,
    pilots_with_logs INTEGER NOT NULL DEFAULT 0,
    logs_left_out    INTEGER NOT NULL DEFAULT 0,
    kills            INTEGER NOT NULL DEFAULT 0,
    losses           INTEGER NOT NULL DEFAULT 0,
    isk_destroyed    DOUBLE PRECISION NOT NULL DEFAULT 0,
    isk_lost         DOUBLE PRECISION NOT NULL DEFAULT 0,
    unpriced_mails   INTEGER NOT NULL DEFAULT 0,
    damage_out       BIGINT NOT NULL DEFAULT 0,
    damage_in        BIGINT NOT NULL DEFAULT 0,
    reps_out         BIGINT NOT NULL DEFAULT 0,
    cap_out          BIGINT NOT NULL DEFAULT 0,
    friendly_fire    BIGINT NOT NULL DEFAULT 0,
    computed_at      TIMESTAMPTZ NOT NULL,
    UNIQUE (op_id, seq)
);

CREATE TABLE IF NOT EXISTS fleet_battle_fights (
    fleet_battle_id BIGINT NOT NULL REFERENCES fleet_battles (id) ON DELETE CASCADE,
    fight_id        BIGINT NOT NULL REFERENCES battle_fights (id) ON DELETE CASCADE,
    PRIMARY KEY (fleet_battle_id, fight_id)
);
CREATE INDEX IF NOT EXISTS fleet_battle_fights_fight ON fleet_battle_fights (fight_id);

CREATE TABLE IF NOT EXISTS fleet_battle_pilots (
    fleet_battle_id BIGINT NOT NULL REFERENCES fleet_battles (id) ON DELETE CASCADE,
    character_id    BIGINT NOT NULL,
    ship_type_id    BIGINT NOT NULL DEFAULT 0,
    damage_out      BIGINT NOT NULL DEFAULT 0,
    damage_in       BIGINT NOT NULL DEFAULT 0,
    reps_out        BIGINT NOT NULL DEFAULT 0,
    kills_on        INTEGER NOT NULL DEFAULT 0,
    died            BOOLEAN NOT NULL DEFAULT FALSE,
    has_log         BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (fleet_battle_id, character_id)
);

CREATE TABLE IF NOT EXISTS fleet_battle_kills (
    fleet_battle_id     BIGINT NOT NULL REFERENCES fleet_battles (id) ON DELETE CASCADE,
    killmail_id         BIGINT NOT NULL,
    killmail_time       TIMESTAMPTZ NOT NULL,
    loss                BOOLEAN NOT NULL,
    victim_character_id BIGINT NOT NULL DEFAULT 0,
    ship_type_id        BIGINT NOT NULL DEFAULT 0,
    value_isk           DOUBLE PRECISION,
    PRIMARY KEY (fleet_battle_id, killmail_id)
);

CREATE TABLE IF NOT EXISTS fleet_battle_series (
    fleet_battle_id BIGINT PRIMARY KEY REFERENCES fleet_battles (id) ON DELETE CASCADE,
    payload         TEXT NOT NULL
);

-- member_credit: the fleet counts toward the owner's own board.
-- public_credit: it also counts in public, which takes a sighting by
-- the fleet read rather than a hand mark. seen_in_fleet lets a real
-- kill score in public even when the fleet was too small or too short
-- to earn attendance points.
CREATE TABLE IF NOT EXISTS fleet_score_pilots (
    op_id         BIGINT NOT NULL REFERENCES ops (id) ON DELETE CASCADE,
    character_id  BIGINT NOT NULL,
    flown_at      TIMESTAMPTZ NOT NULL,
    seen_in_fleet BOOLEAN NOT NULL DEFAULT FALSE,
    member_credit BOOLEAN NOT NULL DEFAULT FALSE,
    public_credit BOOLEAN NOT NULL DEFAULT FALSE,
    PRIMARY KEY (op_id, character_id)
);
CREATE INDEX IF NOT EXISTS fleet_score_pilots_flown ON fleet_score_pilots (flown_at);

-- counts: the mail is not padding, by the killboard leaderboards' rule.
CREATE TABLE IF NOT EXISTS fleet_score_mails (
    op_id        BIGINT NOT NULL REFERENCES ops (id) ON DELETE CASCADE,
    character_id BIGINT NOT NULL,
    killmail_id  BIGINT NOT NULL,
    at           TIMESTAMPTZ NOT NULL,
    loss         BOOLEAN NOT NULL,
    counts       BOOLEAN NOT NULL,
    value_isk    DOUBLE PRECISION NOT NULL DEFAULT 0,
    value_points DOUBLE PRECISION NOT NULL DEFAULT 0,
    PRIMARY KEY (op_id, character_id, killmail_id)
);
CREATE INDEX IF NOT EXISTS fleet_score_mails_at ON fleet_score_mails (at) WHERE counts;

-- scope_kind '' is all of New Eden. board 'pilot' ranks characters
-- within a scope; board 'group' ranks owners across New Eden.
CREATE TABLE IF NOT EXISTS fleet_leaders (
    period      TEXT NOT NULL,
    audience    TEXT NOT NULL,
    scope_kind  TEXT NOT NULL DEFAULT '',
    scope_id    BIGINT NOT NULL DEFAULT 0,
    board       TEXT NOT NULL,
    entity_kind TEXT NOT NULL,
    entity_id   BIGINT NOT NULL,
    place       INTEGER NOT NULL,
    fleets      BIGINT NOT NULL DEFAULT 0,
    kills       BIGINT NOT NULL DEFAULT 0,
    deaths      BIGINT NOT NULL DEFAULT 0,
    isk         DOUBLE PRECISION NOT NULL DEFAULT 0,
    points      BIGINT NOT NULL DEFAULT 0,
    PRIMARY KEY (period, audience, scope_kind, scope_id, board, entity_kind, entity_id)
);
CREATE INDEX IF NOT EXISTS fleet_leaders_place
    ON fleet_leaders (period, audience, scope_kind, scope_id, board, place);
CREATE INDEX IF NOT EXISTS fleet_leaders_entity
    ON fleet_leaders (entity_kind, entity_id, period, audience, board);

-- A deleted fight leaves no change mark of its own, so the fleets built
-- from it are marked here, before the delete removes the link to them.
CREATE OR REPLACE FUNCTION battle_fight_gone_mark_fleets() RETURNS trigger
LANGUAGE plpgsql AS $$
BEGIN
    INSERT INTO fleet_report_state (op_id, dirty_seq)
    SELECT g.op_id, nextval('fleet_report_seq')
    FROM (
        SELECT DISTINCT b.op_id
        FROM fleet_battle_fights l
        JOIN fleet_battles b ON b.id = l.fleet_battle_id
        WHERE l.fight_id = OLD.id
    ) g
    ON CONFLICT (op_id) DO UPDATE SET dirty_seq = excluded.dirty_seq;
    RETURN OLD;
END;
$$;

DROP TRIGGER IF EXISTS battle_fight_gone_mark_fleets ON battle_fights;
CREATE TRIGGER battle_fight_gone_mark_fleets
    BEFORE DELETE ON battle_fights
    FOR EACH ROW EXECUTE FUNCTION battle_fight_gone_mark_fleets();
